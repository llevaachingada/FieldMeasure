#!/usr/bin/env node
/**
 * Generates THIRD-PARTY-NOTICES.md from what is actually installed.
 *
 *   node tools/third-party-notices.mjs          write the file
 *   node tools/third-party-notices.mjs --check  exit 1 if the file is out of date (CI runs this)
 *
 * Run it after any dependency change. "Shipped" packages are the production dependency tree
 * (`npm ls --omit=dev`) minus type-only packages, plus the Workbox modules that vite-plugin-pwa
 * bundles into the service worker. Their full license texts are reproduced, as MIT/ISC/BSD
 * require. Font licenses are read from public/fonts/OFL-*.txt, which ship next to the fonts.
 */
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = join(ROOT, 'THIRD-PARTY-NOTICES.md');
const TYPE_ONLY = new Set(['@types/react', 'csstype']);
const WORKBOX = ['workbox-window', 'workbox-core', 'workbox-precaching', 'workbox-routing', 'workbox-strategies'];
const FONTS = [
  { name: 'Archivo', file: 'Archivo.woff2', role: 'UI text', license: 'OFL-Archivo.txt' },
  { name: 'JetBrains Mono', file: 'JetBrainsMono.woff2', role: 'Numbers and readouts', license: 'OFL-JetBrainsMono.txt' },
];

const pkgDir = (name) => join(ROOT, 'node_modules', name);
const pkgJson = (name) => JSON.parse(readFileSync(join(pkgDir(name), 'package.json'), 'utf8'));
const licenseOf = (pj) => (typeof pj.license === 'string' ? pj.license : pj.license?.type ?? 'UNKNOWN');

function licenseText(name) {
  const file = readdirSync(pkgDir(name)).find((f) => /^licen[cs]e(\.(md|txt))?$/i.test(f));
  return file ? readFileSync(join(pkgDir(name), file), 'utf8').trim() : null;
}

const shipped = execSync('npm ls --omit=dev --all --parseable', { cwd: ROOT, encoding: 'utf8' })
  .split('\n')
  .slice(1)
  .filter(Boolean)
  .map((p) => p.split('/node_modules/').pop())
  .filter((n) => !TYPE_ONLY.has(n));
const runtime = [...new Set([...shipped, ...WORKBOX])].sort();

const root = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const dev = Object.keys(root.devDependencies ?? {}).sort();

const lines = [];
lines.push('# Third-party notices', '');
lines.push('Field Measure ships the third-party software and fonts below. This file is generated by');
lines.push('`node tools/third-party-notices.mjs`; CI fails if it is out of date. Do not edit it by hand.', '');
lines.push('## Shipped in the app', '');
lines.push('| Package | Version | License |', '|---|---|---|');
for (const n of runtime) {
  const pj = pkgJson(n);
  lines.push(`| ${n} | ${pj.version} | ${licenseOf(pj)} |`);
}
lines.push('', '## Fonts', '');
lines.push('Self-hosted in `public/fonts/`. The license text ships next to each font file.', '');
lines.push('| Font | File | Used for | License |', '|---|---|---|---|');
for (const f of FONTS) lines.push(`| ${f.name} | \`${f.file}\` | ${f.role} | SIL Open Font License 1.1 |`);
lines.push('', '## Development tools (not shipped)', '');
lines.push('| Package | Version | License |', '|---|---|---|');
for (const n of dev) {
  const pj = pkgJson(n);
  lines.push(`| ${n} | ${pj.version} | ${licenseOf(pj)} |`);
}
lines.push('', '---', '', '## License texts', '');
for (const n of runtime) {
  const pj = pkgJson(n);
  const text = licenseText(n);
  lines.push(`### ${n} ${pj.version} (${licenseOf(pj)})`, '');
  lines.push(text ? '```text\n' + text + '\n```' : `No license file is included in the package; its package.json declares ${licenseOf(pj)}.`, '');
}
for (const f of FONTS) {
  lines.push(`### ${f.name} (SIL Open Font License 1.1)`, '');
  lines.push('```text\n' + readFileSync(join(ROOT, 'public/fonts', f.license), 'utf8').trim() + '\n```', '');
}
const out = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error('THIRD-PARTY-NOTICES.md is out of date. Run: node tools/third-party-notices.mjs');
    process.exit(1);
  }
  console.log('THIRD-PARTY-NOTICES.md is up to date.');
} else {
  writeFileSync(OUT, out);
  console.log(`Wrote ${OUT} (${runtime.length} shipped packages, ${FONTS.length} fonts).`);
}
